def blank(v):
    return "" if v is None else v


def main():
    with open(os.path.join(HERE, "sauna_traditions.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=T_FIELDS)
        w.writeheader()
        for r in TRADITIONS:
            w.writerow({k: blank(r[k]) for k in T_FIELDS})
    with open(os.path.join(HERE, "sauna_traditions.json"), "w", encoding="utf-8") as f:
        json.dump([{k: (None if r[k] in ("", None) else r[k]) for k in T_FIELDS} for r in TRADITIONS],
                  f, ensure_ascii=False, indent=2)
        f.write("\n")
    with open(os.path.join(HERE, "sauna_headwear.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(H_FIELDS)
        w.writerows(HEADWEAR)
    with open(os.path.join(HERE, "sauna_headwear.json"), "w", encoding="utf-8") as f:
        json.dump([{k: (v or None) for k, v in zip(H_FIELDS, row)} for row in HEADWEAR],
                  f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"traditions: {len(TRADITIONS)} rows, headwear: {len(HEADWEAR)} rows")


if __name__ == "__main__":
    main()
